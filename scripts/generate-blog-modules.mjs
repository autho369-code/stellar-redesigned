// Generates the client-facing blog modules (runs in predev/prebuild).
//
// Evaluates src/data/blog-posts/all-posts.ts (the authoring index, which
// includes future-dated scheduled articles) and emits, under
// src/data/blog-posts/generated/ (gitignored):
//
//   meta.ts             light metadata for every PUBLISHED post — the only
//                       blog data in the main client bundle
//   content/<slug>.ts   one module per published article body; Vite turns
//                       each into its own chunk, fetched only on /blog/:slug
//   content-loaders.ts  slug -> dynamic-import map for those chunks
//
// Future-dated posts are filtered out here, at build time, so unpublished
// content never appears in any client asset (llms.txt promises this). The
// scheduled GitHub workflow rebuilds on publication days, which re-runs this
// with a fresh cutoff.
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { build } from 'esbuild';
import { getChicagoPublicationDate } from './publication-date.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const generatedDir = join(root, 'src/data/blog-posts/generated');

// 1. Evaluate the authoring index (TypeScript) in Node via esbuild.
const tempDir = mkdtempSync(join(tmpdir(), 'stellar-blog-'));
const tempFile = join(tempDir, 'all-posts.mjs');
await build({
  entryPoints: [join(root, 'src/data/blog-posts/all-posts.ts')],
  bundle: true,
  format: 'esm',
  platform: 'node',
  outfile: tempFile,
  logLevel: 'silent',
});
const { allBlogPosts } = await import(pathToFileURL(tempFile).href);
rmSync(tempDir, { recursive: true, force: true });

// 2. Filter to published posts, preserving authoring order (getPostNeighborhoods
//    depends on that order for its stable rotation).
const cutoff = getChicagoPublicationDate();
const published = allBlogPosts.filter((post) => post.date <= cutoff);

const slugs = new Set();
for (const post of published) {
  for (const field of ['slug', 'title', 'metaDescription', 'date', 'author', 'category', 'readTime', 'excerpt', 'content']) {
    if (typeof post[field] !== 'string' || post[field].length === 0) {
      throw new Error(`Post '${post.slug ?? '<unknown>'}' is missing required field '${field}'.`);
    }
  }
  if (!/^[a-z0-9-]+$/.test(post.slug)) {
    throw new Error(`Post slug '${post.slug}' is not filesystem/URL safe.`);
  }
  if (slugs.has(post.slug)) throw new Error(`Duplicate blog slug '${post.slug}'.`);
  slugs.add(post.slug);
}

// 3. Emit the modules.
rmSync(generatedDir, { recursive: true, force: true });
mkdirSync(join(generatedDir, 'content'), { recursive: true });

const banner = (types, from) => `// AUTO-GENERATED by scripts/generate-blog-modules.mjs — do not edit.
// Regenerated on every dev/build; contains only posts published on or before
// the build date (America/Chicago).
import type { ${types} } from '${from}';
`;

const metas = published.map((post) => ({
  slug: post.slug,
  title: post.title,
  metaDescription: post.metaDescription,
  date: post.date,
  ...(post.dateModified ? { dateModified: post.dateModified } : {}),
  author: post.author,
  category: post.category,
  readTime: post.readTime,
  excerpt: post.excerpt,
  ...(post.featuredImage ? { featuredImage: post.featuredImage } : {}),
}));

writeFileSync(
  join(generatedDir, 'meta.ts'),
  `${banner('BlogPostMeta', '../types')}
export const publishedPostMetas: BlogPostMeta[] = ${JSON.stringify(metas, null, 2)};
`,
);

for (const post of published) {
  const content = {
    content: post.content,
    ...(post.sources?.length ? { sources: post.sources } : {}),
  };
  writeFileSync(
    join(generatedDir, 'content', `${post.slug}.ts`),
    `${banner('BlogPostContent', '../../types')}
export const postContent: BlogPostContent = ${JSON.stringify(content, null, 2)};
`,
  );
}

writeFileSync(
  join(generatedDir, 'content-loaders.ts'),
  `${banner('BlogPostContent', '../types')}
export const blogContentLoaders: Record<string, () => Promise<{ postContent: BlogPostContent }>> = {
${published.map((post) => `  '${post.slug}': () => import('./content/${post.slug}'),`).join('\n')}
};
`,
);

console.log(
  `[blog-modules] ${published.length} published post(s) emitted; ` +
  `${allBlogPosts.length - published.length} future-dated post(s) excluded (cutoff ${cutoff}).`,
);
